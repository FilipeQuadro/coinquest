type PixelRect = readonly [x: number, y: number, width: number, height: number, color: string, alpha?: number]

function createPixelTexture(scene: Phaser.Scene, key: string, width: number, height: number, rects: readonly PixelRect[]) {
  if (scene.textures.exists(key)) return

  const texture = scene.textures.createCanvas(key, width, height)
  if (!texture) return
  const context = texture.getContext()
  context.imageSmoothingEnabled = false
  context.clearRect(0, 0, width, height)

  rects.forEach(([x, y, rectWidth, rectHeight, color, alpha = 1]) => {
    context.globalAlpha = alpha
    context.fillStyle = color
    context.fillRect(x, y, rectWidth, rectHeight)
  })

  context.globalAlpha = 1
  texture.refresh()
}

